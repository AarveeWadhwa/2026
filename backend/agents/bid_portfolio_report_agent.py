"""CLI for turning Member 3 workspace JSON into JSON, CSV and Markdown reports."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
from backend.services.bid_portfolio_report import BidPortfolioReport


def main() -> None:
    parser = argparse.ArgumentParser(description="Create a portfolio summary and action register from Member 3 workspace output.")
    parser.add_argument("--input", required=True, help="Path to member3_bid_workspace.json")
    parser.add_argument("--output", default="outputs/member3_portfolio_report.json")
    parser.add_argument("--csv", default="outputs/member3_action_register.csv")
    parser.add_argument("--markdown", default="outputs/member3_portfolio_summary.md")
    args = parser.parse_args()
    source = json.loads(Path(args.input).read_text(encoding="utf-8"))
    if not isinstance(source, dict):
        raise ValueError("Input must be a JSON object generated by the bid workspace pipeline")
    report = BidPortfolioReport().build(source)
    for path in (args.output, args.csv, args.markdown):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    BidPortfolioReport.write_csv(report, args.csv)
    BidPortfolioReport.write_markdown(report, args.markdown)
    print(f"Reported {report['tender_count']} tender(s); saved JSON, CSV, and Markdown outputs.")


if __name__ == "__main__":
    main()
